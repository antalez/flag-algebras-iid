#!/usr/bin/env python3
"""Write Fast/Cert8Data.lean from data/cert8.txt.

The order-8 certificate as Lean numerals, so that the kernel can evaluate checks on it.
Matrices are packed: one natural number per row, fields of fixed width `w` bits, least significant
field first; a signed field `v` is stored as `v + 2^(w-1)`.
"""
import sys
src, dst = sys.argv[1], sys.argv[2]
ft = [0] * 2430; ct = [0] * 1215; sup = [0] * 70; oth = [0] * 230
Lent = []; Y = {}; G = [[0] * 255 for _ in range(255)]
lo = [(0, 0, 0, 0, 1)] * 150; hi = [(0, 0, 0, 0, 1)] * 150
w1 = [(0, 0, 0, 0, 1)] * 8; w2 = [(0, 0, 0, 0, 1)] * 8
sc = {}
for line in open(src):
    v = line.split()
    if not v:
        continue
    kw, x = v[0], [int(t) for t in v[1:]]
    if kw == 'FLAG': ft[x[1] * 10 + x[2]] = x[0]
    elif kw == 'SUP': sup[x[0]] = x[1]
    elif kw == 'OTH': oth[x[0]] = x[1]
    elif kw == 'L': Lent.append((x[0], x[1], tuple(x[2:7])))
    elif kw == 'Y': Y[(x[0], x[1])] = tuple(x[2:7])
    elif kw == 'DEG':
        ct[x[1] * 5 + x[2]] = x[0]; lo[x[0]] = tuple(x[3:8]); hi[x[0]] = tuple(x[8:13])
    elif kw == 'THR': w1[x[0]] = tuple(x[1:6]); w2[x[0]] = tuple(x[6:11])
    elif kw == 'G':
        for j, t in enumerate(x[1:]): G[x[0]][j] = t
    elif kw in ('CBAR', 'GT', 'DN', 'ENC', 'B'): sc[kw] = x
W = [[] for _ in range(300)]
for a, k, e in Lent:
    W[sup[a]].insert(0, (k, e))
for b in range(230):
    W[oth[b]] = [(25 + b, (1, 0, 0, 0, 1))]

def width(vals):
    return max(abs(t) for t in vals).bit_length() + 2
def pack(vals, w):
    off = 1 << (w - 1); r = 0
    for i, t in enumerate(vals):
        f = t + off
        assert 0 <= f < (1 << w)
        r |= f << (w * i)
    return r
def packK(e, w): return pack(list(e), w)

wG = width([t for row in G for t in row])
gCols = [pack([G[k][a] for k in range(255)], wG) for a in range(255)]
# a few entries of Y are much longer than the others: they are stored apart (`yBig`), with a
# placeholder in the packed row
isBig = lambda e: max(abs(t) for t in e).bit_length() > 80
wY = width([t for e in Y.values() if not isBig(e) for t in e])
wB = width([t for e in Y.values() if isBig(e) for t in e] + [1])
ph = (0, 0, 0, 0, 1)
yRows = [pack([t for b in range(255) for t in (ph if isBig(Y[(a, b)]) else Y[(a, b)])], wY)
         for a in range(255)]
yBig = [[(b, pack(list(Y[(a, b)]), wB)) for b in range(255) if isBig(Y[(a, b)])] for a in range(255)]
wS = width([t for l in (lo, hi, w1, w2) for e in l for t in e] + [t for row in W for _, e in row for t in e])

def numlist(name, typ, xs, per=8, hexa=False):
    f = (lambda t: hex(t)) if hexa else str
    out = [f"def {name} : {typ} := ["]
    for i in range(0, len(xs), per):
        out.append("  " + ", ".join(f(t) for t in xs[i:i + per]) + ("," if i + per < len(xs) else ""))
    out.append("]")
    return "\n".join(out) + "\n\n"

with open(dst, 'w') as f:
    f.write("/-!\n# Data of the order-8 certificate (generated by `data/gen_cert8_data.py` from "
            "`data/cert8.txt`)\n\nPacked rows: see `Fast/Pack.lean`.\n-/\n\nnamespace Fast.D8\n\n")
    f.write(f"def wG : Nat := {wG}\n\ndef wY : Nat := {wY}\n\ndef wB : Nat := {wB}\n\n"
            f"def wS : Nat := {wS}\n\n")
    f.write(f"def gT : Nat := {sc['GT'][0]}\n\ndef cbarP : Int := {sc['CBAR'][0]}\n\n"
            f"def cbarQ : Int := {sc['CBAR'][1]}\n\ndef Dn : Int := {sc['DN'][0]}\n\n"
            f"def encLo : Int := {sc['ENC'][0]}\n\ndef encHi : Int := {sc['ENC'][1]}\n\n"
            f"def encM : Nat := {sc['ENC'][2]}\n\ndef B : Int := {sc['B'][0]}\n\n")
    f.write(numlist("ft", "List Nat", ft, 30))
    f.write(numlist("ct", "List Nat", ct, 30))
    f.write("/-- Column `a` of `G`: 255 signed fields of width `wG`. -/\n")
    f.write(numlist("gCols", "List Nat", gCols, 1, True))
    f.write("/-- Row `a` of `Y`: 255 entries of five fields (four signed numerators and a "
            "denominator, stored like a signed field) of width `wY`. -/\n")
    f.write(numlist("yRows", "List Nat", yRows, 1, True))
    f.write("/-- Long entries of `Y`, per row: (column, entry packed with width `wB`), by "
            "increasing column. -/\n")
    f.write("def yBig : List (List (Nat × Nat)) := [\n")
    f.write(",\n".join("  [" + ", ".join(f"({b}, {hex(x)})" for b, x in row) + "]" for row in yBig))
    f.write("\n]\n\n")
    f.write("/-- Sparse rows of `W`: (column, entry packed with width `wS`). -/\n")
    f.write("def wRows : List (List (Nat × Nat)) := [\n")
    f.write(",\n".join("  [" + ", ".join(f"({k}, {hex(packK(e, wS))})" for k, e in row) + "]" for row in W))
    f.write("\n]\n\n")
    for name, l in (("lo", lo), ("hi", hi), ("w1", w1), ("w2", w2)):
        f.write(numlist(name, "List Nat", [packK(e, wS) for e in l], 2, True))
    f.write("end Fast.D8\n")
print("wG", wG, "wY", wY, "wB", wB, "wS", wS)
