#!/usr/bin/env python3
"""Write BeatAvg/Six/Data.lean: the six-point flag certificate as Lean literals.

Inputs: `starting_point/cert_6_json.txt` (flags and rational factors `L_b`, with `Q_b = L_b L_b^T`)
and `data/farkas.txt` (certificates of non-realizability for 5 and 6 points).
Conventions of the Lean checker (`BeatAvg/Six/Eval.lean`):
* a pattern is the list of trits of the quadruples of `Fast.combos n`;
* a flag of `f` sorted points with marked roots has the key `bits * 64 + mask`, where bit `j` of
  `bits` says that candidate `j` of `cand f` succeeds and `mask` is the set of ranks of the roots.
"""
import json, itertools as it, sys, os
from fractions import Fraction

here = os.path.dirname(os.path.abspath(__file__))
cert_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', '..', '..', 'starting_point', 'cert_6_json.txt')
out = os.path.join(here, '..', 'BeatAvg', 'Six', 'Data.lean')

def combos(n): return list(it.combinations(range(n), 4))
C5, C6 = combos(5), combos(6)
certs = {5: {}, 6: {}}
for line in open(os.path.join(here, 'farkas.txt')):
    v = line.split()
    n = int(v[0])
    if n in certs:
        r = list(map(int, v[2:]))
        certs[n][int(v[1])] = [tuple(r[i:i+3]) for i in range(0, len(r), 3)]
def code(P): return sum(t * 3**i for i, t in enumerate(P))
L5 = [P for P in it.product(range(3), repeat=5) if code(P) not in certs[5]]
L5set = set(L5)

# order of the quadruples in the search: the five-point subsets are completed one after another
ord6 = [q for q in C6 if 5 not in q]
for d in (4, 3, 2, 1, 0):
    for q in C6:
        if d not in q and q not in ord6: ord6.append(q)
pos = {q: i for i, q in enumerate(ord6)}
def skip(d, i): return i if i < d else i + 1
restr = {d: [pos[tuple(skip(d, i) for i in q)] for q in C5] for d in range(6)}
need = [max(restr[d]) + 1 for d in range(6)]
L6, used6 = [], {}
def search(acc):
    k = len(acc)
    for d in range(6):
        if need[d] == k and tuple(acc[i] for i in restr[d]) not in L5set: return
    if k == 15:
        P = tuple(acc[pos[q]] for q in C6)
        if code(P) in certs[6]: used6[code(P)] = certs[6][code(P)]
        else: L6.append(P)
        return
    for x in range(3): search(acc + [x])
search([])
assert len(L5) == 30 and len(L6) == 1290

cert = json.load(open(cert_path))
def candidates(n):
    return sorted(tuple(v for v in four if v != target) + (target,)
                  for four in it.combinations(range(n), 4) for target in four[-2:])
def key_of(pattern, marks):
    return sum(1 << j for j, s in enumerate(pattern) if s == 1) * 64 + sum(1 << r for r in marks)
DEN = 10**10
OFF = 10**11
fams = {}
for name, (t, m) in (('A', (2, 2)), ('B', (3, 1)), ('C', (4, 1))):
    keys, blk, rows, bi = [], [], [], 0
    for b in cert['blocks']:
        if b['t'] == t and b['f'] == t + m:
            for fl, row in zip(b['flags'], b['L']):
                keys.append(key_of(fl[0], fl[1])); blk.append(bi)
                r = [Fraction(x) * DEN for x in row]
                assert all(x.denominator == 1 for x in r)
                rows.append([int(x) for x in r])
                assert all(abs(int(x)) < OFF for x in r)
            bi += 1
    assert len(set(keys)) == len(keys)
    fams[name] = (keys, blk, rows)

def nat_list(xs): return "[" + ", ".join(map(str, xs)) + "]"
def int_list(xs): return "[" + ", ".join(str(x) if x >= 0 else f"({x})" for x in xs) + "]"
def cert_lit(c): return "[" + ", ".join(f"({i}, {k}, {w})" for i, k, w in c) + "]"
with open(out, 'w') as f:
    f.write("/-!\n# Data of the six-point flag certificate (generated by `data/gen_six.py`)\n-/\n\n"
            "namespace BeatAvg.Six.D\n\n")
    f.write("/-- The 30 patterns of five points that carry no certificate of non-realizability. -/\n")
    f.write("def L5 : List (List Nat) := [\n" + ",\n".join("  " + nat_list(P) for P in L5) + "\n]\n\n")
    f.write("/-- Certificates of non-realizability for five points, by pattern code. -/\n")
    f.write("def certs5 : List (Nat × List (Nat × Nat × Nat)) := [\n"
            + ",\n".join(f"  ({c}, {cert_lit(v)})" for c, v in sorted(certs[5].items())) + "\n]\n\n")
    f.write("/-- Certificates of non-realizability for six points, by pattern code. -/\n")
    f.write("def certs6 : List (Nat × List (Nat × Nat × Nat)) := [\n"
            + ",\n".join(f"  ({c}, {cert_lit(v)})" for c, v in sorted(used6.items())) + "\n]\n\n")
    f.write("/-- The 1,290 patterns of six points, in the order of the search. -/\n")
    f.write("def L6 : List (List Nat) := [\n" + ",\n".join("  " + nat_list(P) for P in L6) + "\n]\n\n")
    for name, (keys, blk, rows) in fams.items():
        f.write(f"def keys{name} : List Nat := {nat_list(keys)}\n\n")
        f.write(f"def blk{name} : List Nat := {nat_list(blk)}\n\n")
        f.write(f"set_option maxRecDepth 100000 in\n"
                f"/-- Rows of `10^10 L`, each entry shifted by `off` to make it a natural number. -/\n"
                f"def rows{name} : List (List Nat) := [\n"
                + ",\n".join("  " + nat_list([x + OFF for x in r]) for r in rows) + "\n]\n\n")
    f.write(f"/-- Shift of the row entries. -/\ndef off : Int := {OFF}\n\n")
    f.write("/-- `Q = (rows) (rows)^T / den`. -/\ndef den : Int := " + str(DEN * DEN) + "\n\n")
    f.write("/-- The bound `lamP / lamQ`. -/\ndef lamP : Int := 201272564718335614989\n\n"
            "def lamQ : Int := 500000000000000000000\n\nend BeatAvg.Six.D\n")
print("L5", len(L5), "L6", len(L6), "certs5", len(certs[5]), "certs6", len(used6),
      {k: (len(v[0]), len(v[2][0])) for k, v in fams.items()})

# --- the modules that evaluate the certificate on the patterns, a range of patterns per module
CHUNK = 30
root = os.path.join(here, '..', 'BeatAvg', 'Six')
os.makedirs(os.path.join(root, 'Chk'), exist_ok=True)
ranges = [(lo, min(CHUNK, len(L6) - lo)) for lo in range(0, len(L6), CHUNK)]
for k, (lo, cnt) in enumerate(ranges):
    with open(os.path.join(root, 'Chk', f'P{k:02d}.lean'), 'w') as f:
        f.write("import BeatAvg.Six.Eval\n\n/-! Generated by `data/gen_six.py`. -/\n\n"
                "namespace BeatAvg.Six.Chk\n\n"
                "set_option maxRecDepth 100000000 in\nset_option maxHeartbeats 0 in\n"
                f"theorem p{k} : ((D.L6.drop {lo}).take {cnt}).all eval6 = true := by\n"
                "  decide +kernel\n\nend BeatAvg.Six.Chk\n")
with open(os.path.join(root, 'Checks.lean'), 'w') as f:
    f.write("".join(f"import BeatAvg.Six.Chk.P{k:02d}\n" for k in range(len(ranges))))
    f.write('''
/-!
# All patterns of `D.L6` pass the check (generated by `data/gen_six.py`)

The modules `Chk/P*` evaluate `eval6` in the kernel on consecutive ranges of `D.L6`.
-/

namespace BeatAvg.Six

/-- Split a list into consecutive ranges. -/
def pieces (l : List (List Nat)) : List (Nat × Nat) → List (List Nat)
  | [] => []
  | (lo, cnt) :: rest => (l.drop lo).take cnt ++ pieces l rest

def ranges : List (Nat × Nat) :=
  [''' + ", ".join(f"({lo}, {cnt})" for lo, cnt in ranges) + ''']

set_option maxRecDepth 100000000 in
set_option maxHeartbeats 0 in
theorem pieces_eq : pieces D.L6 ranges = D.L6 := by decide +kernel

theorem all_checks : D.L6.all eval6 = true := by
  have h : (pieces D.L6 ranges).all eval6 = true := by
    simp only [pieces, ranges, List.all_append, List.all_nil, Bool.and_true, '''
            + ", ".join(f"Chk.p{k}" for k in range(len(ranges))) + ''', Bool.and_self]
  rwa [pieces_eq] at h

end BeatAvg.Six
''')
print(len(ranges), "check modules")
