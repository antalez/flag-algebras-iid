#!/usr/bin/env python3
"""Write the modules BeatAvg/Cert/S8/*.lean and BeatAvg/Cert/Static8.lean.

The static checks of the order-8 certificate are evaluated by the kernel (`decide +kernel`) in
pieces: one module per range of rows, so that the pieces run in parallel and each one needs a
moderate amount of memory.
"""
import os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'BeatAvg', 'Cert')
os.makedirs(os.path.join(root, 'S8'), exist_ok=True)

def chunks(n, size):
    return [(lo, min(size, n - lo)) for lo in range(0, n, size)]

PARTS = [  # (name, Fast function, number of rows, rows per module)
    ('Psd', 'rowOkI', 255, 16),
    ('Sym', 'symRow', 255, 64),
    ('Int', 'intRow', 300, 10),
]
HEAD = "import Fast.Psd\n\n/-! Generated by `data/gen_static8.py`. -/\n\nnamespace BeatAvg.S8\n\n"
OPTS = "set_option maxRecDepth 100000000 in\nset_option maxHeartbeats 0 in\n"
imports = []
combine = []
for name, fn, n, size in PARTS:
    cs = chunks(n, size)
    for k, (lo, cnt) in enumerate(cs):
        mod = f"{name}{k:02d}"
        imports.append(f"import BeatAvg.Cert.S8.{mod}")
        with open(os.path.join(root, 'S8', mod + '.lean'), 'w') as f:
            f.write(HEAD + OPTS +
                    f"theorem {name.lower()}_{k} :\n    (List.range' {lo} {cnt}).all (Fast.{fn} Fast.cert8) = true := by\n"
                    f"  decide +kernel\n\nend BeatAvg.S8\n")
    split = " ++ ".join(f"List.range' {lo} {cnt}" for lo, cnt in cs)
    lemmas = ", ".join(f"S8.{name.lower()}_{k}" for k in range(len(cs)))
    combine.append(
        f"theorem {name.lower()}_rows : (List.range {n}).all (Fast.{fn} Fast.cert8) = true := by\n"
        f"  have e : List.range {n} = {split} := by\n    decide +kernel\n"
        f"  rw [e]\n  simp only [List.all_append, {lemmas}, Bool.and_self]\n")

with open(os.path.join(root, 'Static8.lean'), 'w') as f:
    f.write("\n".join(imports) + "\n\n")
    f.write('''/-!
# The static checks of the order-8 certificate, evaluated by the kernel

Generated by `data/gen_static8.py`. `Y` is symmetric and `Y - G^T G / 4^gT` is diagonally dominant
(modules `S8/Psd*`, `S8/Sym*`), the tables are integral (`S8/Int*`), and the small checks below.
This module and the modules `S8/*` import only the library `Fast`.
-/

namespace BeatAvg

''')
    f.write("\n".join(combine) + "\n")
    f.write(OPTS + "theorem shape8 : Fast.shapeOk Fast.cert8 = true := by decide +kernel\n\n")
    for t in ('lo', 'hi', 'w1', 'w2'):
        f.write(OPTS + f"theorem int_{t} :\n    Fast.cert8.{t}.toList.all (Fast.K.integralAt Fast.cert8.Dn) = true := by "
                "decide +kernel\n\n")
    f.write(OPTS + "theorem encl8 :\n    Fast.enclosureOk Fast.cert8.encLo Fast.cert8.encHi Fast.cert8.encM = true := by "
            "decide +kernel\n\n")
    f.write(OPTS + "theorem w8 : Fast.wOk Fast.cert8 = true := by decide +kernel\n\n")
    f.write(OPTS + "theorem mult8 : Fast.multOk Fast.cert8 = true := by decide +kernel\n\n")
    f.write(OPTS + "theorem dn8 : decide (0 < Fast.cert8.Dn) = true := by decide +kernel\n\n")
    f.write(OPTS + "theorem cbarQ8 : decide (0 < Fast.cert8.cbarQ) = true := by decide +kernel\n\n")
    f.write(OPTS + "theorem b8 : decide (0 ≤ Fast.cert8.B) = true := by decide +kernel\n\n")
    f.write('''/-- All checks of the order-8 certificate that do not involve patterns. -/
theorem static8 : Fast.staticOk Fast.cert8 = true := by
  have hint : Fast.integralOk Fast.cert8 = true := by
    simp only [Fast.integralOk, int_rows, int_lo, int_hi, int_w1, int_w2, Bool.and_self]
  have hpsd : Fast.psdOk Fast.cert8 = true := by
    simp only [Fast.psdOk, shape8, sym_rows, psd_rows, Bool.and_self]
  simp only [Fast.staticOk, encl8, hint, hpsd, w8, mult8, dn8, cbarQ8, b8, Bool.and_self]

end BeatAvg
''')
print(len(imports), "modules")
